import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(root, 'registry/new-york/ui/beam-vgpu.js')
const result = await build({
  stdin: {
    contents: 'export { clock, effect, frame, frameLoop, init, surface } from "vgpu"',
    resolveDir: root,
    sourcefile: 'border-beam-vgpu-entry.js',
  },
  absWorkingDir: root,
  bundle: true,
  platform: 'browser',
  format: 'esm',
  target: 'es2020',
  minify: true,
  legalComments: 'inline',
  metafile: true,
  write: false,
})

const allowedPackages = new Set(['vgpu', '@vgpu/core', '@vgpu/wgsl', '@vgpu/wgsl-std'])
const notices = new Map()
for (const [input, metadata] of Object.entries(result.metafile.inputs)) {
  if (input === 'border-beam-vgpu-entry.js') continue
  if (metadata.imports.some(entry => entry.external && entry.path !== '<runtime>')) {
    throw new Error(`External dependency in browser runtime: ${input}`)
  }
  let directory = dirname(resolve(root, input))
  while (directory !== dirname(directory)) {
    try {
      const manifest = JSON.parse(readFileSync(resolve(directory, 'package.json'), 'utf8'))
      if (!allowedPackages.has(manifest.name)) {
        throw new Error(`Unexpected browser runtime package: ${manifest.name}`)
      }
      const license = readFileSync(resolve(directory, 'LICENSE'), 'utf8').trim()
      if (manifest.license !== 'MIT') throw new Error(`Unexpected license: ${manifest.name}`)
      notices.set(manifest.name, license)
      break
    } catch (error) {
      if (error.code !== 'ENOENT') throw error
      directory = dirname(directory)
    }
  }
}
const code = result.outputFiles[0].text
if (Object.values(result.metafile.outputs).some(entry => entry.imports.length > 0) ||
    /\b(?:import\s*\(|require\s*\()/.test(code)) {
  throw new Error('The browser runtime must contain no imports or requires')
}
if (!notices.has('vgpu')) throw new Error('Missing VGPU license notice')
const banner = '// Generated by scripts/generate-vgpu-runtime.mjs. Do not edit by hand.\n' +
  [...notices].map(([name, license]) => `/*! ${name}\n${license}\n*/\n`).join('')
writeFileSync(output, banner + code)
console.log(`Wrote ${output} (${code.length} chars; no external runtime dependencies)`)
